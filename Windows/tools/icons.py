# The sidebar toggle: VS Code's codicons (CC BY 4.0), as Cider 1 draws them from the font.
GLYPHS = {"SidebarShown": 0xEBF3, "SidebarHidden": 0xEC02}


def has(v):
    return v is not None and str(v) not in ("none", "None", "transparent") and getattr(v, "alpha", 1) != 0


def convert(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    root_tag = re.search(r"<svg\b[^>]*>", text).group(0)
    if m := re.search(r'viewBox="([^"]+)"', root_tag):
        w, h = [float(v) for v in m.group(1).replace(",", " ").split()][2:]
    else:  # no viewBox: its width and height are the box
        w, h = (float(re.search(rf'\s{a}="([\d.]+)', root_tag).group(1)) for a in ("width", "height"))
        text = text.replace(root_tag, root_tag[:-1] + f' viewBox="0 0 {w:g} {h:g}">', 1)
    # Draw in viewBox units: the root's own width/height ("100%", "1em", "20") would rescale it.
    text = re.sub(r"<svg\b[^>]*>", lambda m: re.sub(r'\s(width|height)="[^"]*"', "", m.group(0)), text, count=1)
    svg = SVG.parse(io.StringIO(text), reify=True, width=w, height=h)
    fills, stroke, stroke_w, rule = [], [], 2.0, "F1 "  # SVG's default fill rule, nonzero
    for e in svg.elements():
        if not isinstance(e, Shape):
            continue
        d = Path(e).d()
        if not d:
            continue
        if has(e.stroke) and e.stroke_width:
            stroke.append(d)
            stroke_w = float(e.stroke_width)
        elif has(e.fill):
            c = e.fill
            if e.values.get("fill-rule") == "evenodd":
                rule = "F0 "
            backdrop = isinstance(e, Rect) and e.width >= w and e.height >= h
            fills.append((d, (c.red + c.green + c.blue) / 3, backdrop))
    if len(fills) > 1:  # a backdrop square (MissingArtwork's grey) is drawn by the app, not the glyph
        fills = [f for f in fills if not f[2]] or fills
    # A few Cider glyphs shade in grey or black inside a white shape: the light parts are the glyph.
    if any(f[1] >= 100 for f in fills):
        fills = [f for f in fills if f[1] >= 100]
    fill = [rule + " ".join(f[0] for f in fills)] if fills else []
    return w, h, " ".join(fill), " ".join(stroke), stroke_w


font = TTFont(f"{root}/less/codicon.ttf")
cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
em = font["head"].unitsPerEm

lines = [
    "// Generated by Windows/tools/icons.py from Cider 1.6.4's icons (src/renderer/assets, views/svg, less/codicon.ttf):",
    "// Feather (MIT), Font Awesome Free 5 (CC BY 4.0), VS Code codicons (CC BY 4.0) and Cider's own (AGPL-3.0).",
    "// Do not edit; regenerate.",
    "namespace Echo.Ui;",
    "",
    "public static class Icons",
    "{",
]
for name, rel in ICONS.items():
    w, h, f, s, sw = convert(f"{root}/{rel}")
    lines.append(f'    public static readonly Icon {name} = new({w:g}, {h:g}, "{f}", "{s}", {sw:g});')
for name, cp in GLYPHS.items():
    pen = SVGPathPen(glyphs)
    glyphs[cmap[cp]].draw(TransformPen(pen, (1, 0, 0, -1, 0, em)))
    lines.append(f'    public static readonly Icon {name} = new({em}, {em}, "F1 {pen.getCommands()}", "", 0);')
lines.append("}")
open(out, "w").write("\n".join(lines) + "\n")
print(f"{len(ICONS) + len(GLYPHS)} icons -> {out}")
